"""
StrategyForge Pine export — turn a candidate's cfg into a Pine Script v6
strategy that mirrors engine.py's SMRT Trap-Aware V4.1 logic.

This closes the loop: optimizer -> adversary -> lineage -> TradingView chart.

What it does
  * Emits a complete `strategy()` script with every cfg value baked in as the
    default of an `input.*` so you can still tweak on the chart.
  * Same fill model as the engine: signal on bar close, fill at next open,
    ATR stop + R:R limit (or ATR trailing), risk-% sizing, reverse on
    opposite signal, percent commission + tick slippage.
  * HTF filter uses request.security on the PREVIOUS completed HTF bar
    (lookahead_on + [1]) — the standard non-repainting idiom, and the same
    thing engine.htf_confirmed() does with `ts // htf_seconds - 1`.
  * Adds alert() calls that emit the JSON davesbridge expects.

What it does NOT do
  * It does not promise a bar-for-bar match. Pine's ta.ema seeds from the
    first value; engine.ema seeds from an SMA of the first n. Pine's daily
    VWAP anchor and Coinbase's UTC day usually agree but not always. The
    original V4.1 matched 73/87 trades under these same differences, so
    expect that order of agreement. ALWAYS run the TradingView List of
    Trades against `python engine.py --pair ... ` before trusting an export.
  * It does not publish to TradingView. There is no API for that. Paste it.

Usage
  python pine_export.py --candidate 1033                      # to stdout
  python pine_export.py --candidate 1033 --out /data/exports/  # writes .pine
  python pine_export.py --strategy 1 --out /data/exports/      # by lineage id
"""

import argparse
import json
import os
import sqlite3
from datetime import datetime, timezone

DB_PATH = os.environ.get("FORGE_DB", "/data/forge.db")


def _b(v):
    return "true" if v else "false"


def _tf_minutes(seconds):
    m = int(seconds) // 60
    if m % 1440 == 0:
        return f"{m // 1440}D"
    return str(m)


def render(cfg, title, source_note):
    if cfg.get("filters"):
        # shadow features (P3.1) come from Python-side data (context feeds,
        # 90-day percentiles) that this template does not reproduce in Pine
        raise SystemExit(f"cannot export: cfg has feature filters {cfg['filters']}; "
                         f"the Pine template has no equivalent for them")
    htf = _tf_minutes(cfg["htf_seconds"])
    return f'''//@version=6
// {title}
// Generated by StrategyForge pine_export.py on {datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%MZ")}
// {source_note}
// Logic mirrors strategyforge/app/engine.py (SMRT Trap-Aware V4.1).
// Verify against the engine's trade list before trusting it.
strategy("{title}", overlay=true,
     initial_capital={cfg["initial_capital"]:.0f},
     default_qty_type=strategy.cash, default_qty_value=0,
     commission_type=strategy.commission.percent, commission_value={cfg["commission_pct"]},
     slippage={int(cfg["slippage_ticks"])},
     pyramiding=0, calc_on_every_tick=false, process_orders_on_close=false)

// ---------------------------------------------------------------- inputs ---
useLongs      = input.bool({_b(cfg["use_longs"])},  "Enable longs",  group="Direction")
useShorts     = input.bool({_b(cfg["use_shorts"])}, "Enable shorts", group="Direction")

rsiLen        = input.int({cfg["rsi_len"]},   "RSI length",     group="RSI")
rsiBuy        = input.float({cfg["rsi_buy"]},  "RSI buy level",  group="RSI")
rsiSell       = input.float({cfg["rsi_sell"]}, "RSI sell level", group="RSI")

emaFastLen    = input.int({cfg["ema_fast"]}, "EMA fast", group="EMA stack")
emaMidLen     = input.int({cfg["ema_mid"]},  "EMA mid",  group="EMA stack")
emaSlowLen    = input.int({cfg["ema_slow"]}, "EMA slow", group="EMA stack")
minEmaSep     = input.float({cfg["min_ema_sep"]}, "Min EMA separation %", group="EMA stack")

adxLen        = input.int({cfg["adx_len"]},    "DI length",     group="ADX")
adxSmooth     = input.int({cfg["adx_smooth"]}, "ADX smoothing", group="ADX")
adxThresh     = input.float({cfg["adx_threshold"]}, "ADX threshold", group="ADX")

dcLen         = input.int({cfg["dc_len"]}, "Donchian length", group="Breakout")

useHTF        = input.bool({_b(cfg["use_htf"])}, "Use HTF EMA filter", group="Higher timeframe")
htfTF         = input.timeframe("{htf}", "HTF", group="Higher timeframe")
htfEmaLen     = input.int({cfg["htf_ema_len"]}, "HTF EMA length", group="Higher timeframe")

useVWAP       = input.bool({_b(cfg["use_vwap"])},   "Require VWAP side", group="Filters")
useVolume     = input.bool({_b(cfg["use_volume"])}, "Require volume",    group="Filters")
volMaLen      = input.int({cfg["vol_ma_len"]}, "Volume MA length", group="Filters")
minRelVol     = input.float({cfg["min_rel_vol"]}, "Min relative volume", group="Filters")

avoidChop     = input.bool({_b(cfg["avoid_chop"])}, "Avoid chop", group="Trap filters")
maxCompress   = input.float({cfg["max_compression"]}, "Max compression (EMA sep %)", group="Trap filters")
avoidLate     = input.bool({_b(cfg["avoid_late"])}, "Avoid late entries", group="Trap filters")
maxDistEma    = input.float({cfg["max_dist_ema"]}, "Max distance from fast EMA %", group="Trap filters")
lookbackBig   = input.int({cfg["lookback_big"]}, "Big-bar lookback", group="Trap filters")
bigBarAtr     = input.float({cfg["big_bar_atr"]}, "Big bar = body > ATR x", group="Trap filters")
maxBigBars    = input.int({cfg["max_big_bars"]}, "Max big bars in lookback", group="Trap filters")
avoidFake     = input.bool({_b(cfg["avoid_fake"])}, "Require breakout confirmation", group="Trap filters")

atrLen        = input.int({cfg["atr_len"]}, "ATR length", group="Risk")
stopAtr       = input.float({cfg["stop_atr"]}, "Stop = ATR x", group="Risk")
rrRatio       = input.float({cfg["rr_ratio"]}, "Reward : risk", group="Risk")
riskPct       = input.float({cfg["risk_pct"]}, "Risk % of equity per trade", group="Risk")
useRiskSizing = input.bool({_b(cfg["use_risk_sizing"])}, "Risk-based sizing", group="Risk")
useTrailing   = input.bool({_b(cfg["use_trailing"])}, "ATR trailing stop instead of fixed target", group="Risk")
trailAtr      = input.float({cfg["trail_atr"]}, "Trail = ATR x", group="Risk")

webhookSecret = input.string("CHANGE_ME", "davesbridge webhook secret", group="Alerts")

// ------------------------------------------------------------ indicators ---
emaF  = ta.ema(close, emaFastLen)
emaM  = ta.ema(close, emaMidLen)
emaS  = ta.ema(close, emaSlowLen)
rsiV  = ta.rsi(close, rsiLen)
[diP, diM, adxV] = ta.dmi(adxLen, adxSmooth)
dcHi  = ta.highest(high, dcLen)[1]
dcLo  = ta.lowest(low, dcLen)[1]
vwapV = ta.vwap(hlc3)
volMa = ta.sma(volume, volMaLen)
atrV  = ta.atr(atrLen)

// previous COMPLETED higher-timeframe bar (non-repainting)
htfClose = request.security(syminfo.tickerid, htfTF, close[1], lookahead=barmerge.lookahead_on)
htfEma   = request.security(syminfo.tickerid, htfTF, ta.ema(close, htfEmaLen)[1], lookahead=barmerge.lookahead_on)

// --------------------------------------------------------------- signals ---
bullStack  = emaF > emaM and emaM > emaS
bearStack  = emaF < emaM and emaM < emaS
bullRsi    = rsiV > rsiBuy + 1
bearRsi    = rsiV < rsiSell - 1
strongLong = adxV > adxThresh + 2
strongShort= adxV > adxThresh + 5
relVol     = volMa > 0 ? volume / volMa : 0.0
volOk      = relVol >= minRelVol
bullBreak  = close > dcHi and close > open
bearBreak  = close < dcLo and close < open
sep        = emaS != 0 ? math.abs(emaF - emaS) / emaS * 100.0 : 0.0
strongSep  = sep >= minEmaSep
slopeLong  = emaS > emaS[1]
slopeShort = emaS < emaS[1]
trending   = adxV > 22 and sep > 1.0
momLong    = close > close[1] and close[1] > close[2]
momShort   = close < close[1] and close[1] < close[2] and close < emaF and adxV > 30
choppy     = adxV <= adxThresh or sep < maxCompress
dist       = emaF != 0 ? math.abs(close - emaF) / emaF * 100.0 : 0.0
bigBar     = math.abs(close - open) > atrV * bigBarAtr
bigBars    = math.sum(bigBar ? 1 : 0, lookbackBig)
late       = dist > maxDistEma * 0.8 or bigBars > maxBigBars
confBull   = bullBreak and close > high[1]
confBear   = bearBreak and close < low[1]
htfLong    = not useHTF or htfClose > htfEma
htfShort   = not useHTF or htfClose < htfEma
trendLong  = strongLong and bullStack and strongSep and adxV > 26 and slopeLong
trendShort = strongShort and bearStack and strongSep and adxV > 28 and slopeShort

longSig  = useLongs and trending and trendLong and bullRsi and momLong and htfLong
     and (not useVWAP or close > vwapV)
     and (not useVolume or volOk)
     and (not avoidChop or not choppy)
     and (not avoidLate or not late)
     and (not avoidFake or confBull)
shortSig = useShorts and trending and trendShort and bearRsi and momShort and htfShort
     and (not useVWAP or close < vwapV)
     and (not useVolume or volOk)
     and (not avoidChop or not choppy)
     and (not avoidLate or not late)
     and (not avoidFake or confBear)

// ---------------------------------------------------------------- orders ---
// signal on this bar's close -> strategy.entry fills at NEXT bar's open,
// exactly like engine.py's `pending` mechanism.
var float stopDist  = na
var float trailDist = na
float riskAmt = strategy.equity * riskPct / 100.0

if longSig and strategy.position_size <= 0
    stopDist  := atrV * stopAtr
    trailDist := atrV * trailAtr
    float qty = useRiskSizing ? riskAmt / math.max(stopDist, syminfo.mintick) : strategy.equity / close
    strategy.entry("L", strategy.long, qty=qty)
    alert('{{"secret":"' + webhookSecret + '","strategy":"{title}","side":"long","symbol":"' + syminfo.ticker + '","tf":"' + timeframe.period + '","price":' + str.tostring(close) + '}}', alert.freq_once_per_bar_close)

if shortSig and strategy.position_size >= 0
    stopDist  := atrV * stopAtr
    trailDist := atrV * trailAtr
    float qty = useRiskSizing ? riskAmt / math.max(stopDist, syminfo.mintick) : strategy.equity / close
    strategy.entry("S", strategy.short, qty=qty)
    alert('{{"secret":"' + webhookSecret + '","strategy":"{title}","side":"short","symbol":"' + syminfo.ticker + '","tf":"' + timeframe.period + '","price":' + str.tostring(close) + '}}', alert.freq_once_per_bar_close)

// exits attach once the position exists (avg price is the real fill)
if strategy.position_size > 0
    if useTrailing
        strategy.exit("L-X", "L", stop=strategy.position_avg_price - stopDist,
             trail_points=trailDist / syminfo.mintick, trail_offset=trailDist / syminfo.mintick)
    else
        strategy.exit("L-X", "L", stop=strategy.position_avg_price - stopDist,
             limit=strategy.position_avg_price + stopDist * rrRatio)
if strategy.position_size < 0
    if useTrailing
        strategy.exit("S-X", "S", stop=strategy.position_avg_price + stopDist,
             trail_points=trailDist / syminfo.mintick, trail_offset=trailDist / syminfo.mintick)
    else
        strategy.exit("S-X", "S", stop=strategy.position_avg_price + stopDist,
             limit=strategy.position_avg_price - stopDist * rrRatio)

// ------------------------------------------------------------------ plots ---
plot(emaF, "EMA fast", color=color.new(color.aqua, 0))
plot(emaM, "EMA mid",  color=color.new(color.orange, 0))
plot(emaS, "EMA slow", color=color.new(color.red, 0))
plotshape(longSig,  "Long signal",  shape.triangleup,   location.belowbar, color=color.green, size=size.small)
plotshape(shortSig, "Short signal", shape.triangledown, location.abovebar, color=color.red,   size=size.small)
'''


def load_cfg(conn, candidate_id=None, strategy_id=None):
    if strategy_id is not None:
        row = conn.execute(
            "SELECT name, pair, tf, params_json, candidate_id, status FROM strategies WHERE id=?",
            (strategy_id,)).fetchone()
        if not row:
            raise SystemExit(f"strategy {strategy_id} not found")
        name, pair, tf, pj, cid, status = row
        return json.loads(pj), f"SF {name}", f"lineage strategy #{strategy_id} status={status} (candidate #{cid}, {pair} {tf})"
    row = conn.execute(
        "SELECT pair, tf, params_json, oos_pf, oos_trades FROM candidates WHERE id=?",
        (candidate_id,)).fetchone()
    if not row:
        raise SystemExit(f"candidate {candidate_id} not found")
    pair, tf, pj, oos_pf, oos_tr = row
    return (json.loads(pj), f"SF c{candidate_id} {pair} {tf}",
            f"optimizer candidate #{candidate_id} on {pair} {tf}, stored OOS pf={oos_pf:.2f} over {oos_tr} trades")


def main():
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--candidate", type=int)
    g.add_argument("--strategy", type=int)
    ap.add_argument("--out", help="directory to write <title>.pine into; omit for stdout")
    args = ap.parse_args()

    conn = sqlite3.connect(DB_PATH)
    cfg, title, note = load_cfg(conn, args.candidate, args.strategy)
    script = render(cfg, title, note)
    if args.out:
        os.makedirs(args.out, exist_ok=True)
        fn = os.path.join(args.out, title.replace(" ", "_").replace("/", "-") + ".pine")
        with open(fn, "w") as f:
            f.write(script)
        print(f"wrote {fn}  ({len(script.splitlines())} lines)")
        print("Next: TradingView -> Pine Editor -> paste -> Add to chart -> Strategy Tester ->")
        print("      List of Trades, compare with:  python engine.py --pair <PAIR> --start <IS> --end <END>")
    else:
        print(script)
    conn.close()


if __name__ == "__main__":
    main()
